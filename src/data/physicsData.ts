const getRawId = (obfuscated: string) => {
  try {
    if (typeof atob !== 'undefined') return atob(obfuscated).split('').reverse().join('');
    if (typeof Buffer !== 'undefined') return Buffer.from(obfuscated, 'base64').toString('utf8').split('').reverse().join('');
    return obfuscated;
  } catch (e) {
    return obfuscated;
  }
};

